#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# TaskWeaver Dev Server Script
#
# Manages a local Symfony dev server for end-to-end development and testing.
# Binds to 0.0.0.0 so the app is accessible via the reverse proxy (Caddy) for
# browser-based visual verification.
#
# The dev server uses a SEPARATE SQLite database (var/data/dev.db) so that the
# real database (var/taskweaver.db) is never touched.
#
# Self-bootstrapping: the `start` command checks for required system packages
# (PHP, extensions, tools), Composer, and project dependencies — installing
# them automatically if missing. This means the script works even after a
# terminal reset/reboot, embracing the self-cleaning container design.
#
# Usage:
#   bin/dev.sh start            Start the dev server (auto-installs deps if needed)
#   bin/dev.sh start --seed     ...and seed the dev DB with sample data
#   bin/dev.sh stop             Stop the dev server
#   bin/dev.sh status           Check if the dev server is running
#   bin/dev.sh restart          Stop and start the dev server
#
# Public URL the dev server is exposed at (reverse proxy). Can be overridden
# via TASKWEAVER_DEV_URL; falls back to TASKWEAVER_DEV_DOMAIN, then an
# example domain.
TASKWEAVER_DEV_DOMAIN="${TASKWEAVER_DEV_DOMAIN:-weaver.example.com}"
TASKWEAVER_DEV_URL="${TASKWEAVER_DEV_URL:-https://${TASKWEAVER_DEV_DOMAIN}}"

# Port assignment (dial-pad mnemonic: W-V-R = 9-8-7):
#   8987 → $TASKWEAVER_DEV_URL
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

# ── Configuration ───────────────────────────────────────────────────────────
PORT=8987
HOST="0.0.0.0"
ENV="dev"
DEV_DB="var/data/dev.db"
DEV_SECRET="dev_secret_not_for_production_use_only"
PID_FILE="var/.dev-server.pid"
LOG_FILE="var/log/dev-server.log"

# Required PHP extensions (checked via php -m)
REQUIRED_PHP_EXTS=(
    ctype
    iconv
    mbstring
    pdo_sqlite
    dom
    SimpleXML
    xml
    intl
    curl
    openssl
)

# Apt packages for PHP + extensions
PHP_APT_PACKAGES=(
    php8.4-cli
    php8.4-common     # ctype, iconv
    php8.4-mbstring
    php8.4-sqlite3    # pdo_sqlite, sqlite3
    php8.4-xml        # dom, SimpleXML, xml
    php8.4-intl
    php8.4-curl
    php8.4-opcache
    php8.4-readline
)

# System tools needed
SYSTEM_TOOLS=(
    git
    unzip
    sqlite3
    curl
)

# Resolve project root (script lives in bin/)
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT"

# Ensure var directory structure exists
mkdir -p var/data var/log

# ── Helpers ─────────────────────────────────────────────────────────────────

is_running() {
    if [[ ! -f "$PID_FILE" ]]; then
        return 1
    fi
    local pid
    pid="$(cat "$PID_FILE")"
    if [[ -z "$pid" ]] || ! kill -0 "$pid" 2>/dev/null; then
        return 1
    fi
    return 0
}

print_status() {
    if is_running; then
        local pid
        pid="$(cat "$PID_FILE")"
        echo "✅ TaskWeaver dev server is RUNNING"
        echo "   PID:     $pid"
        echo "   URL:     http://localhost:${PORT}"
        echo "   Exposed: http://${HOST}:${PORT}"
        echo "   Dev URL: ${TASKWEAVER_DEV_URL}"
        echo "   DB:      ${DEV_DB}"
        echo "   Logs:    ${LOG_FILE}"
    else
        echo "⛔ TaskWeaver dev server is STOPPED"
    fi
}

# ── Dev environment file ──────────────────────────────────────────────────
# Symfony's Runtime (autoload_runtime.php) loads .env.dev via dotenv, and for
# a web request (php -S), a CLI env var (DATABASE_URL=...) does NOT reliably
# win over the committed .env.dev — the value loaded from the dotenv file wins.
# So we write the dev overrides into the git-ignored .env.dev.local, which has
# higher precedence than .env.dev, guaranteeing the separate dev DB is used by
# both CLI commands and web requests.

write_dev_env_local() {
    cat > .env.dev.local <<EOF
# Auto-generated by bin/dev.sh — safe to edit, git-ignored.
DATABASE_URL="sqlite:///%kernel.project_dir%/${DEV_DB}"
EOF
}

# ── Bootstrap ───────────────────────────────────────────────────────────────
# Ensures all system packages, Composer, and project dependencies are present.
# Idempotent — if everything is already installed, checks are fast no-ops.
# This is what makes the script survive terminal resets/reboots.

bootstrap() {
    local needed_packages=()

    # ── Check system tools ──
    for tool in "${SYSTEM_TOOLS[@]}"; do
        if ! command -v "$tool" &>/dev/null; then
            needed_packages+=("$tool")
        fi
    done

    # ── Check PHP and required extensions ──
    local php_needs_install=false
    if ! command -v php &>/dev/null; then
        php_needs_install=true
    else
        for ext in "${REQUIRED_PHP_EXTS[@]}"; do
            if ! php -m 2>/dev/null | grep -iq "^${ext}$"; then
                php_needs_install=true
                break
            fi
        done
    fi

    if [[ "$php_needs_install" == "true" ]]; then
        needed_packages+=("${PHP_APT_PACKAGES[@]}")
    fi

    # ── Install missing packages ──
    if [[ ${#needed_packages[@]} -gt 0 ]]; then
        echo "→ Installing missing system packages: ${needed_packages[*]}…"
        sudo apt-get update -qq
        sudo apt-get install -y -qq "${needed_packages[@]}"
    fi

    # ── Ensure Composer is available ──
    if ! command -v composer &>/dev/null; then
        echo "→ Installing Composer…"
        curl -sS https://getcomposer.org/installer | php
        sudo mv composer.phar /usr/local/bin/composer
        sudo chmod +x /usr/local/bin/composer
    fi

    # ── Ensure project dependencies are installed ──
    if [[ ! -d "vendor/" ]]; then
        echo "→ Installing Composer dependencies…"
        APP_ENV=dev composer install --no-interaction
    fi
}

# ── Commands ────────────────────────────────────────────────────────────────

start() {
    if is_running; then
        echo "⚠️  Dev server is already running (PID $(cat "$PID_FILE"))"
        print_status
        exit 0
    fi

    echo "→ Starting TaskWeaver dev server on ${HOST}:${PORT}…"

    # Self-bootstrap: ensure all dependencies are present
    bootstrap

    # Point the git-ignored .env.dev.local at the separate dev DB
    write_dev_env_local

    # Optional: seed the dev DB with sample data
    local seed=false
    if [[ "${1:-}" == "--seed" ]]; then
        seed=true
    fi

    # Ensure dev database exists
    if [[ ! -f "$DEV_DB" ]]; then
        echo "→ Creating dev database…"
        touch "$DEV_DB"
    fi

    echo "→ Running database migrations…"
    APP_ENV="$ENV" \
    APP_DEBUG=1 \
    APP_SECRET="$DEV_SECRET" \
    DATABASE_URL="sqlite:///%kernel.project_dir%/${DEV_DB}" \
    TASKWEAVER_LLM_URL="${TASKWEAVER_LLM_URL:-http://localhost:11434/v1}" \
    TASKWEAVER_LLM_MODEL="${TASKWEAVER_LLM_MODEL:-dev-model}" \
    TASKWEAVER_LLM_API_KEY="${TASKWEAVER_LLM_API_KEY:-}" \
    TASKWEAVER_ENROLLMENT_TOKEN="${TASKWEAVER_ENROLLMENT_TOKEN:-dev-enrollment-token}" \
    php bin/console doctrine:migrations:migrate --no-interaction 2>&1 | tail -5

    # Seed the dev DB if requested
    if [[ "$seed" == "true" ]]; then
        echo "→ Seeding dev database with sample data…"
        APP_ENV="$ENV" \
        APP_DEBUG=1 \
        APP_SECRET="$DEV_SECRET" \
        DATABASE_URL="sqlite:///%kernel.project_dir%/${DEV_DB}" \
        php bin/console app:seed --no-interaction 2>&1 | tail -5
    fi

    echo "→ Clearing dev cache…"
    APP_ENV="$ENV" \
    APP_DEBUG=1 \
    APP_SECRET="$DEV_SECRET" \
    DATABASE_URL="sqlite:///%kernel.project_dir%/${DEV_DB}" \
    php bin/console cache:clear 2>&1 | tail -3

    echo "→ Starting PHP dev server…"
    APP_ENV="$ENV" \
    APP_DEBUG=1 \
    APP_SECRET="$DEV_SECRET" \
    DATABASE_URL="sqlite:///%kernel.project_dir%/${DEV_DB}" \
    DEFAULT_URI="${TASKWEAVER_DEV_URL}" \
    TASKWEAVER_LLM_URL="${TASKWEAVER_LLM_URL:-http://localhost:11434/v1}" \
    TASKWEAVER_LLM_MODEL="${TASKWEAVER_LLM_MODEL:-dev-model}" \
    TASKWEAVER_LLM_API_KEY="${TASKWEAVER_LLM_API_KEY:-}" \
    TASKWEAVER_ENROLLMENT_TOKEN="${TASKWEAVER_ENROLLMENT_TOKEN:-dev-enrollment-token}" \
    nohup php -S "${HOST}:${PORT}" -t public/ 2>&1 > "$LOG_FILE" 2>&1 &

    local pid=$!
    echo "$pid" > "$PID_FILE"

    # Give it a moment to boot
    sleep 2

    if is_running; then
        echo ""
        print_status
    else
        echo "❌ Failed to start dev server. Check logs:"
        echo "   ${LOG_FILE}"
        tail -20 "$LOG_FILE" 2>/dev/null || true
        rm -f "$PID_FILE"
        exit 1
    fi
}

stop() {
    if ! is_running; then
        echo "⚠️  Dev server is not running."
        rm -f "$PID_FILE"
        exit 0
    fi

    local pid
    pid="$(cat "$PID_FILE")"
    echo "→ Stopping dev server (PID ${pid})…"
    kill "$pid" 2>/dev/null || true

    # Wait for graceful shutdown
    local count=0
    while kill -0 "$pid" 2>/dev/null && [[ $count -lt 10 ]]; do
        sleep 0.5
        count=$((count + 1))
    done

    # Force kill if still alive
    if kill -0 "$pid" 2>/dev/null; then
        echo "→ Process didn't exit gracefully, sending SIGKILL…"
        kill -9 "$pid" 2>/dev/null || true
    fi

    rm -f "$PID_FILE"
    echo "✅ Dev server stopped."
}

restart() {
    stop
    sleep 1
    start "${1:-}"
}

# ── Main ────────────────────────────────────────────────────────────────────

usage() {
    echo "Usage: bin/dev.sh {start|stop|status|restart}"
    echo ""
    echo "Commands:"
    echo "  start            Start the dev server (auto-installs deps if needed)"
    echo "  start --seed     ...and seed the dev DB with sample data"
    echo "  stop             Stop the dev server"
    echo "  status           Check if the dev server is running"
    echo "  restart          Stop and start the dev server"
    echo "  restart --seed   Stop and start, then seed the dev DB"
    exit 1
}

case "${1:-}" in
    start)   start "${2:-}" ;;
    stop)    stop ;;
    status)  print_status ;;
    restart) restart "${2:-}" ;;
    *)       usage ;;
esac
